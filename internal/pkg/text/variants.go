func PickRandom(key string, lastUsed string) string {
	list, ok := variants[key]
	if !ok {
		return "..."
	}

	for range 10 {
		pick := list[rand.IntN(len(list))]
		if pick != lastUsed {
			return pick
		}
	}

	return list[0]
}
